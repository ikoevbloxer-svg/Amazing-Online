    /** Короткие формы для обращения «товарищ ...». */
    public static String addressForm(String rank) {
        String r = rank.toLowerCase();
        r = r.replace(" внутренней службы", "").replace(" полиции", "").replace(" юстиции", "");
        if (r.startsWith("юрист") || r.contains("советник")) return rank.toLowerCase();
        return r;
    }

